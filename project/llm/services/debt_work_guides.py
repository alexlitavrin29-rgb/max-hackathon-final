def route(question, selected_topic=None):
    """Prepared selection; several independent spheres require a human choice."""
    q = str(question or '').casefold().replace('ё', 'е')
    has = lambda pattern: bool(re.search(pattern, q))
    clauses = re.split(r'[,;.!?\n]|\b(?:но|однако)\b', q)
    ids = []
    for clause in clauses:
        match = lambda pattern: bool(re.search(pattern, clause))
        def affirmative(pattern):
            for event in re.finditer(pattern, clause):
                prefix, suffix = clause[:event.start()], clause[event.end():]
                if re.search(r'\bне\s+(?:(?:нуж\w*|хочу|ищу|предлага\w*)\s+)?$', prefix):
                    continue
                if re.match(r'\s+не\s+(?:нуж\w*|интерес\w*)', suffix):
                    continue
                return True
            return False
        if (match(r'кредит|за[её]м|займ|мфо') and match(r'нечем|не\s+могу\s+плат|долг|задолж|просроч')
                and not match(r'нет\s+(?:\w+\s+)?долг|долг\w*\s+нет|погашен')):
            ids.append('debt_credit')
        if (match(r'коммун|жк[ух]|квитанц') and match(r'долг|задолж|нечем|не\s+могу\s+плат')
                and not match(r'нет\s+долг|долг\w*\s+нет|погашен')):
            ids.append('debt_utilities')
        if match(r'коллектор|взыскател'):
            ids.append('debt_collection')
        if (match(r'зарплат|заработн\w*\s+плат')
                and match(r'не\s+выплат|не\s+плат|задерж')
                and not match(r'\bне\s+задерж|\bнет\s+задерж')):
            ids.append('work_wages')
        if match(r'зарплат|заработн\w*\s+плат') and match(r'удержа|вычли|вычита') and not match(r'не\s+удержа'):
            ids.append('work_deductions')
        if (match(r'заставля|принужда|требу') and match(r'увол|собственн\w*\s+желан')
                and not match(r'не\s+(?:заставля|принужда|требу)')):
            ids.append('work_dismissal')
        lodging = affirmative(r'работ\w*\s+с\s+(?:предоставлением\s+)?(?:проживан\w*|жиль\w*|комнат\w*)')
        if lodging:
            ids.append('work_lodging_contract')
        elif (affirmative(r'(?:работал|работаю|работа[ею]м|отработал|предлага\w*|поработа\w*).{0,50}без\s+(?:оформлен|догов)')
              or affirmative(r'неоплачен\w*\s+пробн|неоплачиваем\w*\s+пробн|пробн\w*\s+(?:день|смен\w*)[^.!?]*без\s+оплат')):
            ids.append('work_unregistered')
        if affirmative(r'сопроводительн\w*\s+письм\w*') and not match(r'учебн|для\s+(?:учеб|урока)|реферат|курсов'):
            ids.append('cover_letter')
    ids = list(dict.fromkeys(ids))
    if not ids:
        return None
    topics = list(dict.fromkeys(TOPIC_OVERRIDES[i] for i in ids))
    # Explicit independent goals matter; incidental words like a housing
    # condition or employment document do not request another workflow.
    from .planner_retrieval import work_search_requested
    search_work = any(work_search_requested(clause) for clause in clauses)
    if search_work and 'work' not in topics:
        topics.append('work')
    for topic, pattern in (
        ('documents', r'(?:восстанов|получ|замен|оформ)\w*\s+(?:\w+\s+)?(?:паспорт|снилс)|восстанов\w*\s+документ'),
        ('housing', r'(?:ищу|найти)\s+(?:\w+\s+)?(?:квартир|жиль|комнат)|'
                    r'(?:снять|снимать|арендовать)\s+(?:\w+\s+){0,2}(?:квартир|жиль|комнат)'),
        ('study', r'хочу\s+(?:учиться|поступить)|нужн\w*\s+обучени'),
        ('benefits', r'(?:оформить|получить)\s+(?:\w+\s+)?(?:пособи|выплат)'),
    ):
        if topic not in topics and any(re.search(pattern, clause)
                and not re.search(r'не\s+(?:хочу|нужно|ищу|найти|оформить|получить|восстановить)', clause)
                for clause in clauses):
            topics.append(topic)
    near_housing_payment=('work_wages' in ids and has(r'комнат|аренд|жиль')
                          and has(r'скор|ближайш') and has(r'плат|оплат'))
    if near_housing_payment:
        if 'housing' not in topics:
            topics.append('housing')
    if has(r'хочу\s+(?:составить\s+)?бюджет') and 'budget' not in topics:
        topics.append('budget')
    if len(topics) > 1 and not selected_topic:
        question=('Что сейчас важнее: решить задержку зарплаты или ближайшую оплату жилья?'
                  if near_housing_payment and set(topics)=={'work','housing'}
                  else 'Что сейчас важнее решить? Выбери, с чего начнём.')
        return dict(kind='choice', choices=topics, question=question)
    if selected_topic:
        ids = [i for i in ids if TOPIC_OVERRIDES[i] == selected_topic]
    if not ids:
        return None
    result = dict(kind='material', id=ids[0], ids=ids[:3], topic=TOPIC_OVERRIDES[ids[0]])
    if 'work_lodging_contract' in ids:
        result['related'] = ['documents', 'housing']
    return result
