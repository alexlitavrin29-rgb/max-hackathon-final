def route(question, selected_topic=None, *, question_id=None, answer=None):
    q = str(question or '').casefold().replace('ё','е')
    a = str(answer or '').casefold().replace('ё','е').strip()
    has = lambda p: bool(re.search(p,q))
    lost = has(r'(?:потер|утер|утрат|украл)\w*.{0,25}(?:все\s+документ|документ\w*\s+и\s+паспорт)|без\s+всех\s+документ')
    account = has(r'госуслуг|есиа')
    recovery = account and has(r'не\s+могу\s+войти|не\s+получа\w*\s+войти|нет\s+доступ|доступ\w*\s+(?:нет|к\s+стар)|восстанов\w*\s+доступ|забыл\w*\s+парол')
    create = account and not recovery and has(r'впервые|перв\w*\s+(?:учетн|запис|регистрац)|зарегистрир|создать\s+(?:учетн|аккаунт)|нет\s+(?:учетн|аккаунт)')
    no_reg = has(r'нет\s+(?:регистраци|прописки)|без\s+(?:регистраци|прописки)')
    clinic = has(r'прикреп|поликлиник')
    refusal = any(not re.search(r'\bне\s+$', q[:event.start()])
                  for event in re.finditer(r'\b(?:отказал\w*|отказыва\w*|не\s+принял\w*|не\s+принима\w*|не\s+записал\w*|отправил\w*\s+(?:из\s+(?:регистратур\w*|поликлиник\w*|больниц\w*)\s+)?домой)\b', q))
    explicit_care = has(r'поликлиник|регистратур|врач|медицинск\w*\s+помощ|медпомощ')
    other_refusal = refusal and not explicit_care and has(r'работ|паспорт|документ|заявлен|пособи|выплат|учеб|колледж|вуз|жиль|квартир')
    denial = refusal and not other_refusal and (explicit_care or has(r'полис|\bомс\b') or selected_topic == 'health')
    if refusal and not denial and not other_refusal and not selected_topic:
        return dict(kind='choice', choices=['health', 'work', 'documents'], question='С какой сферой связан отказ в приёме? Выбери подходящую тему.')
    care_visit = has(r'регистратур|талон|к\s+врач|на\s+прием')
    policy_request = has(r'(?:оформ|получ|узна|уточн)\w*.{0,25}(?:полис|омс)|сведен\w*.{0,25}полис')
    policy = (has(r'полис|\bомс\b')
              and has(r'нет|потер|утрат|получ|оформ|узнать|не\s+зна|неизвест|уточн|сведен')
              and (not care_visit or policy_request))
    attach = clinic and not denial and (has(r'прикреп|переех|переезд') or no_reg)
    identifiers=[]
    if lost: identifiers.append('documents_all_lost')
    if recovery: identifiers.append('gosuslugi_access')
    elif create: identifiers.append('gosuslugi_create')
    if denial: identifiers.append('care_denial')
    elif attach: identifiers.append('clinic_attachment')
    elif policy: identifiers.append('oms_policy')
    if no_reg and not identifiers:
        if a in {'не знаю','неизвестно'}:
            return dict(kind='material', id='registration_barrier', topic='documents', information_only=True)
        if not a:
            return dict(kind='access_clarify', question_id='documents_kind', question='Для какой услуги мешает отсутствие регистрации: паспорт, Госуслуги или медицинская помощь?')
        if re.search(r'поликлиник|медицин|полис|омс',a):
            identifiers.append('oms_policy' if re.search(r'полис|омс',a) else 'clinic_attachment')
        elif 'паспорт' in a or 'услуг' in a:
            identifiers.append('registration_barrier')
        else:
            return dict(kind='access_gap')
    if not identifiers and (selected_topic == 'health' or question_id == 'health_kind' or has(r'нужн\w*\s+медицинск\w*\s+помощ')):
        if question_id == 'health_kind' and a:
            if re.search(r'отказ|не\s+принял|не\s+принима', a): identifiers.append('care_denial')
            elif re.search(r'полис|омс', a): identifiers.append('oms_policy')
            elif re.search(r'прикреп', a): identifiers.append('clinic_attachment')
            else: return dict(kind='access_gap', medical=True)
        else:
            return dict(kind='access_clarify', question_id='health_kind', question='Нужна помощь с полисом ОМС, прикреплением или отказом в приёме?')
    if no_reg and question_id == 'documents_kind' and re.search(r'поликлиник|медицин|полис|омс', a):
        selected_topic = 'health'
    if not identifiers:
        return None
    topics=list(dict.fromkeys(TOPIC_OVERRIDES[i] for i in identifiers))
    if other_refusal:
        extra = 'work' if has(r'работ') else 'documents' if has(r'паспорт|документ|заявлен') else None
        if extra and extra not in topics: topics.append(extra)
    from .debt_work_guides import route as debt_work_route
    from .planner_retrieval import work_search_requested
    other=debt_work_route(q)
    if other:
        topics.extend(t for t in (other['choices'] if other['kind']=='choice' else [other['topic']]) if t not in topics)
    if work_search_requested(q) and 'work' not in topics:
        topics.append('work')
    benefits = any(not re.search(r'\bне\s+(?:хочу\s+)?$', q[:event.start()])
                   for event in re.finditer(r'(?:оформ(?:ить|лять)|получ(?:ить|ать))\s+(?:пособи|выплат)', q))
    if benefits and 'benefits' not in topics:
        topics.append('benefits')
    for topic,pattern in [('housing',r'хочу\s+(?:снять|найти)\s+жиль|ищу\s+квартир'),('study',r'хочу\s+(?:учиться|поступить)'),('budget',r'хочу\s+(?:составить\s+)?бюджет')]:
        if has(pattern) and topic not in topics: topics.append(topic)
    if benefits and selected_topic == 'benefits' and question_id == 'topic_choice':
        return dict(kind='benefit_kind')
    if len(topics)>1 and not selected_topic:
        return dict(kind='choice',choices=topics,question='Что сейчас важнее решить? Выбери, с чего начнём.')
    if selected_topic:
        identifiers=[i for i in identifiers if TOPIC_OVERRIDES[i]==selected_topic]
    if not identifiers:
        return None
    identifier=identifiers[0]
    if identifier=='documents_all_lost':
        if question_id!='documents_kind' or not a:
            return dict(kind='access_clarify',question_id='documents_kind',question='Был утрачен ранее выданный вам паспорт гражданина РФ? Ответьте «да», «нет» или «не знаю», без реквизитов.')
        if not re.match(r'да\b',a): return dict(kind='access_gap')
    if identifier=='gosuslugi_create':
        if question_id!='documents_kind' or not a:
            return dict(kind='access_clarify',question_id='documents_kind',question='Вам уже исполнилось 14 лет? Ответьте «да», «нет» или «не знаю», без даты рождения.')
    result=dict(kind='material',id=identifier,topic=TOPIC_OVERRIDES[identifier])
    if identifier=='gosuslugi_create' and not re.match(r'да\b',a): result['information_only']=True
    if identifier=='gosuslugi_access' and has(r'жиль|жилищ|квартир'): result['related']=['housing']
    return result
