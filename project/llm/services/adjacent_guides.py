def needs_support(question):
    q = str(question or '').casefold().replace('ё', 'е')
    # A profession or an explicitly declined consultation is not a request
    # for personal support. Unclear cases retain the normal topic classifier.
    if re.search(r'\bне\s+(?:нужен|нужна|нужны|ищу)\s+(?:(?:бесплатн|личн)\w*\s+)?психолог|'
                 r'\bне\s+хочу\s+(?:(?:говорить|поговорить|общаться)\s+с\s+)?психолог', q):
        return False
    return bool(re.search(r'психологическ\w*\s+(?:помощ|поддерж|консультац)|'
                          r'(?:помощ|поддерж|консультац)\w*\s+(?:у\s+)?психолог|'
                          r'\b(?:нужен|хочу|ищу|найти|телефон)\s+(?:(?:бесплатн|хорош|опытн|детск|квалифицированн)\w*\s+){0,2}психолог|'
                          r'(?:поговорить|написать|обратиться)\s+(?:с\s+|к\s+)?психолог|'
                          r'мне\s+тяжело|тревожно|обсудить\s+переживания|'
                          r'поговорить\s+с\s+кем|по\s+телефону\s+говорить\s+не\s+могу', q))


