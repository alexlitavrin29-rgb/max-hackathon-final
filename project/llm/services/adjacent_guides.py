def basic_need_goals(question):
    """Identify broad livelihood requests while leaving concrete disputes alone."""
    q = str(question or '').casefold().replace('ё', 'е')
    has = lambda pattern: bool(re.search(pattern, q))
    goals = set()
    requested = lambda pattern: any(not re.search(r'\bне\s+(?:(?:очень|особенно|совсем|больше)\s+){0,2}$', q[:match.start()])
                                    for match in re.finditer(pattern, q))
    # Income is requested by an action/question, not merely mentioned as
    # already earned, being received, or expected on a particular date.
    income_infinitive = (r'получ(?:ить|ать)|доста(?:ть|вать)|добы(?:ть|вать)|'
                         r'найти|взять|заработать|зарабатывать')
    income_action = (rf'{income_infinitive}|получ(?:у|ишь|ит|им|ите|ат)|'
                     r'доста(?:ну|нешь|нет|нем|нете|нут)|заработ(?:аю|аешь|ает|аем|аете|ают)')
    question_prefix = r'\b(?:как|где|можно)\s+(?:(?:мне|нам|я|мы|можно|лучше|легально|быстро|реально|вообще)\s+){0,3}'
    desire_prefix = (r'\b(?:хочу|хотим|хотел(?:а|и)?|планирую|планируем|собираюсь|собираемся|нужно|надо|помоги(?:те)?|помочь)\s+'
                     r'(?:(?:бы|мне|нам|начать|стабильно|легально|быстро|дополнительно)\s+){0,3}')
    money_object = r'(?:деньг\w*|денег|(?:источник\s+)?доход\w*)'
    money = (requested(rf'(?:(?:{question_prefix}|{desire_prefix}|\b(?:мне|нам)\s+бы\s+)(?:{income_action})|'
                 rf'(?:^|[.!?;])\s*(?:{income_infinitive}))\s+(?:\w+\s+){{0,3}}{money_object}')
             or requested(r'нужны\s+деньг\w*|нужен\s+(?:источник\s+)?доход\w*|на\s+что\s+(?:мне\s+)?жить')
             or requested(r'\b(?:как|где)\s+(?:(?:мне|можно|легально|быстро)\s+){0,3}заработать\s*[.!?]*\s*$'))
    money_specific = has(r'зарплат|заработн\w*\s+плат|кредит|займ|долг|мошен|укра|вернуть|возврат|банк|карт[уыае]|'
                         r'пособи|пенси|маткапитал|крипт|биткоин|налог|инвест|казино|ставк')
    if money and not money_specific:
        goals.add('income')
    housing = has(r'(?:получ\w*|нужн\w*|хочу)\s+(?:(?!(?:справк|выписк|сведени|документ)\w*\b)\w+\s+){0,4}(?:жиль(?:е|я|ю|ем)\b|квартир\w*)|'
                  r'как\s+(?:мне\s+)?найти\s+(?:\w+\s+){0,2}(?:жиль\w*|квартир\w*)|'
                  r'како\w*\s+жиль\w*|(?:жиль\w*|квартир\w*)\s+(?:мне\s+)?полож\w*|'
                  r'ищ\w*\s+где\s+жить|негде\s+(?:жить|ночевать|переночевать)|(?:жить|ночевать)\s+негде|'
                  r'нет\s+(?:своего\s+)?жилья')
    housing_specific = has(r'очеред|списк|госжиль|государств|сирот|переез|переех|аренд|снять|снимать|найм|наем|'
                           r'заявлен|договор|выплат|сертифик|субсиди|коммунал|купить|покупк|ипотек')
    if housing and not housing_specific and not has(r'\bне\s+(?:нужн\w*|хочу\s+получ\w*)\s+(?:жиль\w*|квартир\w*)'):
        goals.add('housing')
    return goals


def prepared_route(question, selected_topic=None, *, question_id=None, answer=None):
    """Use a reviewed guide only when the question names a clear dependent step."""
    q = str(question or '').lower().replace('ё', 'е')
    has = lambda pattern: bool(re.search(pattern, q))
    from .study_guides import route as study_route
    study = study_route(q, selected_topic, question_id=question_id, answer=answer)
    if study:
        return study
    from .access_guides import route as access_route
    access = access_route(q, selected_topic, question_id=question_id, answer=answer)
    if access:
        return access
    from .debt_work_guides import route as debt_work_route
    debt_work = debt_work_route(q, selected_topic)
    if debt_work:
        return debt_work
    money = money_route(q, selected_topic)
    if money:
        return money
    unknown = str(answer or '').strip().casefold().rstrip('.!?') in {'не знаю', 'не помню', 'неизвестно', 'не понимаю'}
    if question_id == 'housing_kind' and unknown:
        return dict(kind='material', id='housing_start', topic='housing')
    if has(r'выплат\w*\s+(?:за|на)\s+квартир\w*'):
        if selected_topic == 'housing':
            return dict(kind='material', id='hq_state_housing_certificate', topic='housing')
        if selected_topic == 'benefits':
            return dict(kind='material', id='utility_subsidy', topic='benefits')
        return dict(kind='comparison', id='housing_start', topic='housing', choices=['housing', 'benefits'],
                    question='Ты имеешь в виду жилищный сертификат вместо квартиры или субсидию на оплату ЖКУ?',
                    choice_titles={'housing': 'Сертификат вместо квартиры', 'benefits': 'Субсидия на оплату ЖКУ'})
    goals = basic_need_goals(q)
    if goals:
        if goals == {'income'} and has(r'не\s+ищу\s+работ|не\s+хочу\s+работать'):
            return dict(kind='material', id='social_assistance', topic='benefits')
        identifiers = [identifier for goal, identifier, topic in
                       [('income', 'income_start', 'work'), ('housing', 'housing_start', 'housing')]
                       if goal in goals and (not selected_topic or selected_topic == topic)]
        if identifiers:
            return dict(kind='material', id=identifiers[0], ids=identifiers,
                        topic='work' if identifiers[0] == 'income_start' else 'housing')
    if selected_topic:
        if (selected_topic == 'housing' and has(r'колледж|учеб|обучен|поступ')
                and has(r'друг\w*\s+город|переез') and has(r'жиль|общежит|комнат')):
            return dict(kind='material', id='student_housing', topic='housing',
                        related=['study'])
        return None
    if (has(r'паспорт') and has(r'потер|утер|утрат')
            and has(r'наш[еа]л\w*\s+работ|работ\w*\s+уже\s+наш[еа]л')):
        return dict(kind='material', id='passport_new_job', topic='documents')
    if (has(r'жиль|жилищ|квартир|очеред|список') and has(r'документ')
            and has(r'остал\w*') and has(r'учрежден|центр\w*\s+содейств|детдом')):
        return dict(kind='material', id='housing_docs_left', topic='housing')
    if has(r'госуслуг') and has(r'не\s+могу\s+войти|не\s+получа\w*\s+войти|доступ|парол|код'):
        return dict(kind='material', id='gosuslugi_access', topic='documents',
                    related=['housing'] if has(r'жиль|жилищ|квартир') else [])
    if (has(r'работ') and has(r'проживан|жиль|комнат')
            and has(r'без\s+(?:оформлен|догов)')):
        return dict(kind='material', id='work_lodging_contract', topic='work')
    if has(r'статус') and has(r'не\s+(?:знаю|понимаю)|како\w*\s+.*статус|подтвержд'):
        return dict(kind='material', id='status_orientation', topic='documents',
                    related=['help'] if has(r'кто\s+помож|помощ') else [])
    if (has(r'выплат') and has(r'повли|сохран|прекрат')
            and has(r'работ|подработ|заработ')):
        return dict(kind='benefit_kind')
    if (has(r'работаю|уже\s+работ\w*|текущ\w*\s+работ')
            and has(r'колледж|учеб|обучен') and has(r'совмещ|законч')):
        return dict(kind='material', id='work_study_current', topic='study')
    if (has(r'зарплат') and has(r'задерж|не\s+плат|не\s+выплат')
            and has(r'комнат|аренд|жиль') and has(r'скор|ближайш')
            and has(r'плат|оплат')):
        return dict(kind='choice', choices=['work', 'housing'],
                    question='Что сейчас важнее: решить задержку зарплаты или ближайшую оплату жилья?')
    if (has(r'учиться|учеб|обучен') and has(r'работ')
            and has(r'\bили\b|сравн|что\s+.*подход|что\s+лучше')
            and not has(r'жиль|жилищ|квартир|комнат')):
        return dict(kind='comparison', choices=['study', 'work'], id='work_study_choice',
                    question='Что изучим первым: доход от работы сейчас или обучение и профессию?')
    return None


def _affirmative_event(question, pattern):
    for match in re.finditer(pattern, question):
        # Check the event's own prefix. A denied theft must not cancel a
        # separate real debit; the word «мне» is not the negation «не».
        if not re.search(r'\bне\s+(?:(?:был[аио]?|были|успели|смогли)\s+)?$', question[:match.start()]):
            return True
    return False


def basic_needs(question):
    q = str(question or '').casefold().replace('ё', 'е')
    pattern = (r'нет\s+денег\s+на\s+(?:еду|(?:самое\s+)?необходимое)|нечего\s+есть|нет\s+еды|'
               r'не\s+хватает\s+(?:денег\s+)?на\s+еду|денег\s+нет\s+на\s+сегодня|сегодня\s+нет\s+денег')
    direct = any(not re.match(r'\s+не\s+(?:проблем|актуальн)', q[match.end():])
                 for match in re.finditer(pattern, q))
    food_without_money_today = (re.search(r'сегодня|сейчас|прямо\s+сейчас', q)
                                and re.search(r'нужн\w*\s+ед[ау]|нечего\s+есть|нет\s+еды', q)
                                and re.search(r'нет\s+денег|денег\s+нет|не\s+хватает\s+денег', q))
    return bool(direct or food_without_money_today)


def _ongoing_fraud(question):
    for clause in re.split(r'[,;.!?\n]|\b(?:но|однако)\b', question):
        if re.search(r'\bне\s+(?:звон|треб|обман|продолж)|закончил|прекрат|больше\s+не|'
                     r'реферат|изучаю|стать[яю]|раньше|вчера', clause):
            continue
        action = re.search(r'звон(?:ит|ят)|требу(?:ет|ют)|прос(?:ит|ят)|продолжа\w*|вымога\w*', clause)
        financial = re.search(r'мошенни|обман|код|деньг|перев(?:од|ести)', clause)
        # Only an explicit continuation without a new named caller inherits
        # the earlier fraud context. An ordinary call is not financial risk.
        resumed_call = re.fullmatch(r'\s*(?:сейчас\s+)?снова\s+звонят\s*', clause)
        recent_risk = (re.search(r'сейчас|прямо', clause)
                       and re.search(r'мошенни|обман|код|списал|украл|перев(?:од|ести)', clause))
        if action and financial or recent_risk or resumed_call:
            return True
    return False


def money_route(question, selected_topic=None):
    """Conservative prepared money intents; multiple goals keep the human choice."""
    q = str(question or '').casefold().replace('ё', 'е')
    has = lambda pattern: bool(re.search(pattern, q))
    loss = _affirmative_event(q, r'\b(?:списал\w*|украл\w*|украли|похит\w*|перевел\w*\s+деньг)')
    fraud = has(r'мошенни|обман') or _affirmative_event(q, r'\b(?:передал|сообщил)\w*\s+(?:\w+\s+){0,2}код')
    fraud = fraud or (loss and has(r'деньг|счет|карт') and has(r'украл|украли|похит'))
    fraud = fraud and not has(r'мошенничеств\w*\s+нет|\bне\s+мошенник')
    code = has(r'код|данные\s+карт|банковск\w*\s+данн')
    restricted = has(r'банк|карт|счет') and has(r'огранич|блокир|заблок|недоступ')
    need_today = basic_needs(q)
    budget = has(r'бюджет|нерегулярн\w*\s+доход|доход\w*\s+(?:приходит\s+)?нерегуляр|распредел\w*\s+деньг|финансов\w*\s+подушк|созда\w*\s+резерв')
    funds = r'(?:деньг\w*|денег|доход\w*|накоплени[яй]|накопленное|сбережени[яй])\b'
    preserve = r'(?:сохранить|сохранять|сберечь|хранить|отложить|копить|не\s+потерять)'
    allocate = r'(?:распределить|распределять|разложить|распланировать|планировать|спланировать)'
    management = has(rf'{preserve}\s+(?:(?!(?:паспорт|карт|документ|парол|код)\w*\b)\w+\s+){{0,3}}{funds}')
    management = management or has(rf'{allocate}\s+(?:\w+\s+){{0,2}}(?:{funds}|расход\w*|трат\w*)')
    management = management or (has(funds) and has(rf'\b(?:как|хочу|нужно)\s+(?:(?:мне|нам|их|его|это)\s+){{0,3}}{allocate}\b'))
    specific_money = has(r'банк|банков|карт|счет|парол|код|инвест|биткоин|крипт|акци|облигаци|вклад|депозит|кредит|займ|долг|потеря[лн]\w*|укра\w*|списа\w*')
    budget = budget or (management and not specific_money)
    budget = budget and not has(r'бюджет\s+не\s+нуж|не\s+нуж\w*\s+бюджет|бюджет\w*\s+аренд')
    if selected_topic == 'budget':
        budget = True
    ongoing = fraud and _ongoing_fraud(q)
    identifier, topic = (('fraud_money_loss', 'help') if fraud and loss else
                         ('fraud_shared_code', 'help') if fraud and (code or ongoing) else
                         ('bank_access', 'help') if restricted and not loss else
                         ('money_today', 'help') if need_today else
                         ('money_budget', 'budget') if budget else (None, None))
    if not identifier:
        return None
    if selected_topic and selected_topic != topic and not ongoing:
        return None
    alternatives = [name for name, pattern in (
        ('budget', r'бюджет|нерегулярн\w*\s+доход|распредел\w*\s+деньг'),
        ('work', r'(?:нужн\w*|ищу|найти|хочу)\s+(?:\w+\s+){0,2}работ'),
        ('housing', r'(?:нужн\w*|ищу|найти|хочу)\s+(?:\w+\s+){0,2}(?:жиль|квартир)'),
        ('documents', r'(?:нужн\w*|восстанов|получить)\w*\s+(?:\w+\s+){0,2}(?:паспорт|документ)'),
        ('study', r'хочу\s+(?:учиться|поступить)|нужн\w*\s+обучени'),
        ('benefits', r'(?:оформить|получить)\s+(?:пособи|выплат)'),
    ) if name != topic and has(pattern)]
    if topic == 'budget' and 'income' in basic_need_goals(q) and 'work' not in alternatives:
        alternatives.append('work')
    if alternatives and not selected_topic and not ongoing:
        return dict(kind='choice', choices=[topic, *alternatives],
                    notice='money_today' if need_today else None,
                    question='Что сейчас важнее решить? Выбери, с чего начнём.')
    return dict(kind='material', id=identifier, topic=topic, immediate=ongoing)


def nodes(config):
    by_id = {node.get('id'): node for node in config.get('nodes', [])}
    branches = {branch['id']: branch for branch in config.get('branches', [])}
    values = {'role': 'child'}
    result = []
    for guide in GUIDES:
        replacement = guide['id'] in {'study_transfer', 'study_debts'}
        anchor = by_id.get(guide['id'] if replacement else guide['anchor'])
        if ((guide['id'] in by_id and not replacement) or not anchor or anchor.get('content_status') in
                {'unverified_reference', 'draft', 'archived'} or not _allowed(anchor, branches, values)
                or not _path(config, anchor['id'], values)):
            continue
        result.append(dict(id=guide['id'], title=guide['title'], kind='message',
                           branch=anchor['branch'], content_status='source_checked_reference',
                           text=guide['text'], tasks=guide['tasks'], sources=[], buttons=[]))
    return result
